// Package designtokens turns design/tokens.json, the design guidebook's
// values (design/README.md), into Go source for the app.
package designtokens

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"sort"
	"strings"
)

// Generate returns native_tokens_gen.go for the tokens in raw.
func Generate(raw []byte) ([]byte, error) {
	var t struct {
		Color map[string]map[string]string `json:"color"`
		Tint  orderedStrings               `json:"tint"`
		Font  struct {
			Display struct {
				Weight                        int
				Tracking, Leading, LeadingCJK float64
			}
		} `json:"font"`
		Size   map[string]json.RawMessage `json:"size"`
		Radius map[string]json.RawMessage `json:"radius"`
		Motion struct {
			Fast, Base, Slow, Morph int
			Press, Grow             float64
			Ease                    string
		} `json:"motion"`
		Product map[string]int                                          `json:"product"`
		Shadow  map[string]json.RawMessage                              `json:"shadow"`
		Wash    struct{ Dark, Light, Bar, CardDark, CardLight float64 } `json:"wash"`
	}
	if err := json.Unmarshal(raw, &t); err != nil {
		return nil, err
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by go run ./design/gen from design/tokens.json; DO NOT EDIT.\n\n")
	b.WriteString("package main\n\nimport (\n\t\"time\"\n\n\t\"github.com/egoist/mygo/ui\"\n)\n\n")
	for _, mode := range []string{"dark", "light"} {
		roles := t.Color[mode]
		if len(roles) == 0 {
			return nil, fmt.Errorf("tokens: no %s colours", mode)
		}
		fmt.Fprintf(&b, "// token%s is the guidebook's %s appearance.\nvar token%s = nativePalette{\n", title(mode), mode, title(mode))
		for _, k := range sorted(roles) {
			fmt.Fprintf(&b, "\t%s: ui.Hex(%q),\n", k, roles[k])
		}
		if mode == "dark" {
			b.WriteString("\tdark: true,\n")
		}
		b.WriteString("}\n\n")
	}
	b.WriteString("// tokenTints are the header tints in the guidebook's order; a page's tint\n// is chosen by hashing into this list, so the order is part of the design.\nvar tokenTints = []ui.Color{")
	for i, kv := range t.Tint {
		if i > 0 {
			b.WriteString(", ")
		}
		fmt.Fprintf(&b, "ui.Hex(%q)", kv[1])
	}
	b.WriteString("}\n\nconst (\n")
	px := func(group string, m map[string]json.RawMessage) error {
		for _, k := range sorted(m) {
			var n float64
			if json.Unmarshal(m[k], &n) == nil {
				fmt.Fprintf(&b, "\ttoken%s%s = %g\n", group, title(k), n)
				continue
			}
			var f struct{ Min, Max float64 }
			if json.Unmarshal(m[k], &f) == nil && f.Max > 0 {
				fmt.Fprintf(&b, "\ttoken%s%sMin = %g\n\ttoken%s%sMax = %g\n", group, title(k), f.Min, group, title(k), f.Max)
			}
		}
		return nil
	}
	if err := px("Size", t.Size); err != nil {
		return nil, err
	}
	if err := px("Radius", t.Radius); err != nil {
		return nil, err
	}
	d := t.Font.Display
	fmt.Fprintf(&b, "\ttokenDisplayWeight = %d\n\ttokenDisplayLeading = %g\n\ttokenDisplayLeadingCJK = %g\n", d.Weight, d.Leading, d.LeadingCJK)
	fmt.Fprintf(&b, "\ttokenMotionFast = %d * time.Millisecond\n\ttokenMotionBase = %d * time.Millisecond\n\ttokenMotionSlow = %d * time.Millisecond\n\ttokenMotionMorph = %d * time.Millisecond\n", t.Motion.Fast, t.Motion.Base, t.Motion.Slow, t.Motion.Morph)
	fmt.Fprintf(&b, "\ttokenPressScale = %g\n\ttokenGrowScale = %g\n", t.Motion.Press, t.Motion.Grow)
	for _, k := range sorted(t.Product) {
		fmt.Fprintf(&b, "\ttokenProduct%s = %d\n", title(k), t.Product[k])
	}
	b.WriteString(")\n")
	// The easing curve, cubic-bezier(x1, y1, x2, y2) in the tokens, as CSS has it.
	var x1, y1, x2, y2 float64
	if _, err := fmt.Sscanf(strings.ReplaceAll(t.Motion.Ease, " ", ""), "cubic-bezier(%g,%g,%g,%g)", &x1, &y1, &x2, &y2); err != nil {
		return nil, fmt.Errorf("tokens: motion ease %q is not a cubic-bezier: %w", t.Motion.Ease, err)
	}
	fmt.Fprintf(&b, "\n// tokenMotionEase is the tokens' easing curve, as the website's CSS uses it.\nvar tokenMotionEase = ui.CubicBezier(%g, %g, %g, %g)\n", x1, y1, x2, y2)
	fmt.Fprintf(&b, "\n// Washes: how strongly a tint or cover colours the chrome.\nconst (\n\ttokenWashDark = %g\n\ttokenWashLight = %g\n\ttokenWashBar = %g\n\ttokenWashCardDark = %g\n\ttokenWashCardLight = %g\n)\n", t.Wash.Dark, t.Wash.Light, t.Wash.Bar, t.Wash.CardDark, t.Wash.CardLight)
	b.WriteString("\n// Elevations: offset y, blur and the opacity of black.\nvar (\n")
	for _, k := range sorted(t.Shadow) {
		if strings.HasPrefix(k, "$") {
			continue
		}
		if k == "lightScale" {
			var v float64
			if err := json.Unmarshal(t.Shadow[k], &v); err != nil {
				return nil, fmt.Errorf("tokens: shadow lightScale: %w", err)
			}
			fmt.Fprintf(&b, "\ttokenShadowLightScale = float32(%g)\n", v)
			continue
		}
		var v [3]float64
		if err := json.Unmarshal(t.Shadow[k], &v); err != nil {
			return nil, fmt.Errorf("tokens: shadow %s: %w", k, err)
		}
		fmt.Fprintf(&b, "\ttokenShadow%s = nativeShadow{%g, %g, %g}\n", title(k), v[0], v[1], v[2])
	}
	b.WriteString(")\n")
	return format.Source(b.Bytes())
}

// orderedStrings is a JSON object of strings that keeps its keys' order.
type orderedStrings [][2]string

func (o *orderedStrings) UnmarshalJSON(data []byte) error {
	dec := json.NewDecoder(bytes.NewReader(data))
	if _, err := dec.Token(); err != nil {
		return err
	}
	for dec.More() {
		k, err := dec.Token()
		if err != nil {
			return err
		}
		var v string
		if err := dec.Decode(&v); err != nil {
			return err
		}
		*o = append(*o, [2]string{k.(string), v})
	}
	return nil
}

func title(s string) string { return strings.ToUpper(s[:1]) + s[1:] }

func sorted[V any](m map[string]V) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}
